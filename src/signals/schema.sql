PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS events (
 seq INTEGER PRIMARY KEY AUTOINCREMENT, brand TEXT NOT NULL, event_id TEXT NOT NULL,
 kind TEXT NOT NULL, occurred INTEGER NOT NULL, received INTEGER NOT NULL,
 body TEXT NOT NULL, hash TEXT NOT NULL, UNIQUE(brand,event_id));
CREATE TABLE IF NOT EXISTS decisions (
 id TEXT PRIMARY KEY, brand TEXT NOT NULL, account TEXT NOT NULL, as_of INTEGER NOT NULL,
 input_seq INTEGER NOT NULL, body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS outbox (
 id TEXT PRIMARY KEY, decision TEXT NOT NULL REFERENCES decisions(id), destination TEXT NOT NULL,
 brand TEXT NOT NULL, account TEXT NOT NULL, payload TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'pending', attempts INTEGER NOT NULL DEFAULT 0,
 next_at INTEGER NOT NULL DEFAULT 0, detail TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS publication (
 id INTEGER PRIMARY KEY CHECK(id=1), body TEXT NOT NULL, hash TEXT NOT NULL);

